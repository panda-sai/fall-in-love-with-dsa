// ---- code from the book ----
void selectionSort(vector<int>& arr) {
    int n = arr.size();
    for (int i = 0; i < n - 1; i++) {
        int minIdx = i;
        for (int j = i + 1; j < n; j++) {
            if (arr[j] < arr[minIdx]) {
                minIdx = j;
            }
        }
        swap(arr[i], arr[minIdx]);
    }
}

// ---- a small test, so you can run this example ----
int main() {
    vector<int> a = {5, 2, 8, 1, 3};
    selectionSort(a);
    for (int x : a) cout << x << " ";
    cout << endl;
}
